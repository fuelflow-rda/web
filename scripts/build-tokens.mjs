#!/usr/bin/env node
/**
 * Generates every token file from design-tokens/tokens.json, the single source
 * of the design system for web and mobile.
 *
 * Writes:
 *   src/styles/tokens.css    CSS custom properties, light and dark
 *   src/styles/theme.css     Tailwind 4 theme: colour utilities, fonts, sizes, radii
 *   src/theme/tokens.ts      the same values for TypeScript (antd theme, charts)
 *   <mobile>/src/theme/tokens.ts   light values for React Native, when the
 *                            mobile repo is found (../relai-mobile, or --mobile <dir>)
 *
 * Usage:
 *   node scripts/build-tokens.mjs            write the files
 *   node scripts/build-tokens.mjs --check    exit 1 if any file is missing or stale
 *
 * The three apps are separate repositories, so mobile gets a generated copy.
 * Its header carries a hash of the body; relai-mobile/scripts/check-tokens.mjs
 * fails if the file was edited by hand.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const CHECK = args.includes('--check');
const mobileArg = args.includes('--mobile') ? args[args.indexOf('--mobile') + 1] : null;
const mobileRoot = resolve(root, mobileArg ?? '../relai-mobile');

const SOURCE = 'design-tokens/tokens.json';
const tokens = JSON.parse(readFileSync(join(root, SOURCE), 'utf8'));
const strip = (o) => Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith('$')));

// ---------------------------------------------------------------- validation
const problems = [];
const HEX = /^#[0-9A-F]{6}([0-9A-F]{2})?$/;
const themed = strip(tokens.color.themed);
const fixed = strip(tokens.color.fixed);
for (const [name, v] of Object.entries(themed)) {
  for (const mode of ['light', 'dark']) {
    if (!HEX.test(v[mode] ?? '')) problems.push(`color.themed.${name}.${mode} must be #RRGGBB or #RRGGBBAA in capitals`);
  }
}
for (const [name, v] of Object.entries(fixed)) if (!HEX.test(v)) problems.push(`color.fixed.${name} must be #RRGGBB or #RRGGBBAA in capitals`);
for (const name of Object.keys(fixed)) if (name in themed) problems.push(`${name} is both themed and fixed`);
const sizes = tokens.type.size;
for (const set of ['web', 'app']) {
  for (const [name, s] of Object.entries(strip(tokens.type[set]))) {
    if (!sizes.includes(s.size)) problems.push(`type.${set}.${name}: size ${s.size} is not in type.size`);
    if (!(s.tracking in tokens.type.tracking)) problems.push(`type.${set}.${name}: unknown tracking ${s.tracking}`);
    if (!(s.family in tokens.font.family)) problems.push(`type.${set}.${name}: unknown family ${s.family}`);
    if (!tokens.font.$weights[s.family].includes(s.weight)) problems.push(`type.${set}.${name}: ${s.family} has no weight ${s.weight}`);
  }
}
const radiusScale = strip(tokens.radius.scale);
for (const [role, step] of Object.entries(tokens.radius.role)) if (!(step in radiusScale)) problems.push(`radius.role.${role} points at missing step ${step}`);
if (problems.length) {
  console.error(`${SOURCE} has problems:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

// ---------------------------------------------------------------- shared bits
const px = (n) => `${n}px`;
const rem = (n) => `${n / 16}rem`;
const families = strip(tokens.font.family);
const tracking = strip(tokens.type.tracking);
const sizeTokens = strip(tokens.size);
const breakpoints = strip(tokens.breakpoint);
const radiusPx = (step) => (step === 'full' ? '9999px' : px(radiusScale[step]));
const banner = (comment) =>
  `${comment} GENERATED by scripts/build-tokens.mjs from ${SOURCE}. Do not edit: change the JSON and run \`pnpm run tokens\`.`;

// next/font exposes each family as a CSS variable (see src/app/fonts.ts).
const FONT_VARS = { display: '--font-instrument-serif', sans: '--font-geist', mono: '--font-geist-mono' };

// ---------------------------------------------------------------- tokens.css
function tokensCss() {
  const lines = [`/* ${banner('').trim()} */`, '', ':root {', '  color-scheme: light;'];
  for (const [n, v] of Object.entries(themed)) lines.push(`  --${n}: ${v.light};`);
  lines.push('', '  /* The same in both themes. */');
  for (const [n, v] of Object.entries(fixed)) lines.push(`  --${n}: ${v};`);
  lines.push('', '  /* Sizes */');
  for (const [n, v] of Object.entries(sizeTokens)) lines.push(`  --size-${n}: ${px(v)};`);
  lines.push('}', '', ":root[data-theme='dark'] {", '  color-scheme: dark;');
  for (const [n, v] of Object.entries(themed)) if (v.dark !== v.light) lines.push(`  --${n}: ${v.dark};`);
  lines.push('}', '');
  return lines.join('\n');
}

// ---------------------------------------------------------------- theme.css
function themeCss() {
  const L = [`/* ${banner('').trim()} */`, '', '/* Colour utilities resolve to the themed custom properties in tokens.css. */', '@theme inline {'];
  for (const n of [...Object.keys(themed), ...Object.keys(fixed)]) L.push(`  --color-${n}: var(--${n});`);
  L.push('}', '', '/* `static`: emitted even when no utility uses them, so plain CSS can read them too. */', '@theme static {');
  for (const [k, f] of Object.entries(families)) L.push(`  --font-${k}: var(${FONT_VARS[k]}), ${f.fallback};`);
  L.push('');
  for (const s of sizes) {
    L.push(`  --text-${s}: ${px(s)};`);
    L.push(`  --text-${s}--line-height: ${tokens.type.lineHeight};`);
  }
  L.push('');
  for (const [n, v] of Object.entries(tracking)) L.push(`  --tracking-${n}: ${v};`);
  L.push('');
  for (const [n, v] of Object.entries(strip(tokens.font.weight))) L.push(`  --font-weight-${n}: ${v};`);
  L.push('');
  for (const step of Object.keys(radiusScale)) L.push(`  --radius-${step}: ${radiusPx(step)};`);
  for (const [role, step] of Object.entries(tokens.radius.role)) if (role !== 'full') L.push(`  --radius-${role}: ${radiusPx(step)};`);
  L.push('');
  L.push(`  --spacing: ${rem(tokens.space.unit)};`);
  for (const [n, v] of Object.entries(breakpoints)) L.push(`  --breakpoint-${n}: ${rem(v)};`);
  L.push('}', '');
  L.push('/* Named text styles from the Typography board (web scale). */');
  for (const [name, s] of Object.entries(strip(tokens.type.web))) {
    L.push(`@utility type-${name} {`);
    L.push(`  font-family: var(--font-${s.family});`);
    L.push(`  font-size: ${px(s.size)};`);
    L.push(`  line-height: ${px(s.lineHeight)};`);
    L.push(`  font-weight: ${s.weight};`);
    L.push(`  letter-spacing: var(--tracking-${s.tracking});`);
    if (s.uppercase) L.push('  text-transform: uppercase;');
    L.push('}');
  }
  L.push('');
  return L.join('\n');
}

// ---------------------------------------------------------------- web tokens.ts
const ts = (v) => JSON.stringify(v, null, 2).replace(/"([a-zA-Z_][a-zA-Z0-9_]*)":/g, '$1:');
function webTs() {
  const light = Object.fromEntries(Object.entries(themed).map(([n, v]) => [n, v.light]));
  const dark = Object.fromEntries(Object.entries(themed).map(([n, v]) => [n, v.dark]));
  const webType = Object.fromEntries(Object.entries(strip(tokens.type.web)).map(([n, s]) => [n, { ...s, tracking: tracking[s.tracking] }]));
  return [
    banner('//'),
    '',
    '/** Themed colours, by theme. Names match the CSS custom properties and the Pencil variables. */',
    `export const themedColors = ${ts({ light, dark })} as const;`,
    '',
    '/** Colours that are the same in both themes. */',
    `export const fixedColors = ${ts(fixed)} as const;`,
    '',
    'export type ThemeMode = keyof typeof themedColors;',
    'export type ThemedColor = keyof typeof themedColors.light;',
    'export type FixedColor = keyof typeof fixedColors;',
    '',
    `export const fontFamily = ${ts(Object.fromEntries(Object.entries(families).map(([k, f]) => [k, f.name])))} as const;`,
    '',
    `export const fontWeight = ${ts(strip(tokens.font.weight))} as const;`,
    '',
    `export const fontSizes = ${JSON.stringify(sizes)} as const;`,
    `export const defaultLineHeight = ${tokens.type.lineHeight};`,
    '',
    `export const textStyles = ${ts(webType)} as const;`,
    '',
    `export const radius = ${ts(Object.fromEntries([...Object.keys(radiusScale).map((s) => [`r${s}`, s === 'full' ? 9999 : radiusScale[s]]), ...Object.entries(tokens.radius.role).map(([r, s]) => [r, s === 'full' ? 9999 : radiusScale[s]])]))} as const;`,
    '',
    `export const size = ${ts(sizeTokens)} as const;`,
    '',
    `export const spaceUnit = ${tokens.space.unit};`,
    `export const breakpoints = ${ts(breakpoints)} as const;`,
    '',
  ].join('\n');
}

// ---------------------------------------------------------------- mobile tokens.ts
const RN_WEIGHT = { 400: 'Regular', 500: 'Medium', 600: 'SemiBold', 700: 'Bold' };
const camel = (n) => n.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const RN_PREFIX = { display: 'InstrumentSerif', sans: 'Geist', mono: 'GeistMono' };
function mobileTs() {
  const light = Object.fromEntries(Object.entries(themed).map(([n, v]) => [n, v.light]));
  const fontFiles = Object.fromEntries(
    Object.entries(tokens.font.$weights).map(([fam, ws]) => [fam, Object.fromEntries(ws.map((w) => [w, `${RN_PREFIX[fam]}_${w}${RN_WEIGHT[w]}`]))]),
  );
  const em = (v, size) => Math.round(parseFloat(v) * size * 100) / 100;
  const appType = Object.fromEntries(
    Object.entries(strip(tokens.type.app)).map(([n, s]) => [
      n,
      {
        fontFamily: fontFiles[s.family][s.weight],
        fontSize: s.size,
        lineHeight: s.lineHeight,
        letterSpacing: em(tracking[s.tracking], s.size),
        ...(s.uppercase ? { textTransform: 'uppercase' } : {}),
      },
    ]),
  );
  const body = [
    '/** Colours for the light theme, the only theme the app has. The Pencil and web name in camelCase: surface-muted is surfaceMuted. */',
    `export const color = ${ts(Object.fromEntries(Object.entries({ ...light, ...fixed }).map(([n, v]) => [camel(n), v])))} as const;`,
    'export type ColorName = keyof typeof color;',
    '',
    '/**',
    ' * Font family names as registered by useFonts in app/_layout.tsx. React Native',
    ' * picks a weight by family name, so each weight is its own family.',
    ' */',
    `export const fontFamily = ${ts(fontFiles)} as const;`,
    '',
    `export const fontSizes = ${JSON.stringify(sizes)} as const;`,
    'export type FontSize = (typeof fontSizes)[number];',
    `/** Pencil's default line height, for text that has no named style. */`,
    `export const lineHeightFor = (size: FontSize): number => Math.round(size * ${tokens.type.lineHeight});`,
    '',
    `/** Tracking in em; multiply by the font size for React Native's letterSpacing. */`,
    `export const tracking = ${ts(Object.fromEntries(Object.entries(tracking).map(([n, v]) => [camel(n), parseFloat(v)])))} as const;`,
    '',
    '/** Named text styles from the Typography board (attendant app scale, in pt). */',
    `export const textStyles = ${ts(appType)} as const;`,
    '',
    `/** One ${tokens.space.unit}pt unit; space(4) is 16. Halves are allowed: space(1.5) is 6. */`,
    `export const space = (steps: number): number => steps * ${tokens.space.unit};`,
    '',
    `export const radius = ${ts(Object.fromEntries([...Object.keys(radiusScale).map((s) => [`r${s}`, s === 'full' ? 9999 : radiusScale[s]]), ...Object.entries(tokens.radius.role).map(([r, s]) => [camel(r), s === 'full' ? 9999 : radiusScale[s]])]))} as const;`,
    '',
    `export const size = ${ts(Object.fromEntries(Object.entries(sizeTokens).map(([n, v]) => [camel(n), v])))} as const;`,
    '',
  ].join('\n');
  const hash = createHash('sha256').update(body).digest('hex').slice(0, 16);
  return `${banner('//').replace('scripts/build-tokens.mjs', 'relai-web/scripts/build-tokens.mjs').replace(SOURCE, `relai-web/${SOURCE}`).replace('run `pnpm run tokens`', 'run `pnpm run tokens` in relai-web')}\n// body-sha256: ${hash}\n\n${body}`;
}

// ---------------------------------------------------------------- write or check
const outputs = [
  [join(root, 'src/styles/tokens.css'), tokensCss()],
  [join(root, 'src/styles/theme.css'), themeCss()],
  [join(root, 'src/theme/tokens.ts'), webTs()],
];
if (existsSync(join(mobileRoot, 'package.json'))) outputs.push([join(mobileRoot, 'src/theme/tokens.ts'), mobileTs()]);
else if (mobileArg) {
  console.error(`No mobile app at ${mobileRoot}`);
  process.exit(1);
}

let stale = 0;
for (const [file, content] of outputs) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
  const name = relative(root, file);
  if (CHECK) {
    if (current !== content) {
      stale++;
      console.error(`stale: ${name}`);
    }
  } else if (current !== content) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    console.log(`wrote ${name}`);
  } else {
    console.log(`unchanged ${name}`);
  }
}
if (CHECK) {
  if (stale) {
    console.error('Run `pnpm run tokens` and commit the result.');
    process.exit(1);
  }
  console.log(`tokens: ${outputs.length} files up to date`);
}
